#!/usr/bin/env python3
"""Render native harness adapters from the core and the project overlay.

  python3 harness/core/scripts/render_adapters.py [--check] [--root REPO]

The core (skills/, roles/, adapters/models.json) is vendored in the repository, normally at
harness/core; the overlay is harness/project or $HARNESS_PROJECT (project.json roles,
roles/*.md, skills/, rules/, models.json). --root defaults to the Git checkout of the current
directory. --check validates sources and generated files without changing the filesystem.

Skills are linked, overlay over core: a project skill named like a core skill replaces it and
the run says so. Roles are composed into the agent files themselves (core role, then the
overlay's roles/<name>.md under "## Project specifics"; a project role is its overlay body):
the text lands in the subagent's system prompt, cached with it, so a dispatch spends no tool
call and no round trip on reading its role, and the tokens are the same as one Read would add.
No third-party packages are needed.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import posixpath
import re
import sys
import tomllib

sys.path.insert(0, str(Path(__file__).resolve().parent))
import project  # noqa: E402


SAFE_NAME = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
SANDBOXES = ("read-only", "workspace-write")
# Generated files of any core location, including the layout before the core was vendored.
OWNED = r"Generated by (?:\S+/)?scripts/render_adapters\.py; edit canonical sources\."
OWNED_MD = re.compile(rf"<!-- {OWNED} -->")
OWNED_TOML = re.compile(rf"# {OWNED}")
LEGACY_SCRIPTS = "harness/scripts"


class Layout:
    """Where the core and the overlay sit, as paths relative to the repository root."""

    def __init__(self, root: Path):
        self.root = root
        self.core_rel = core_location(root)
        overlay = project.overlay_dir(root)
        if not overlay.is_relative_to(root):
            raise ValueError(f"the overlay {overlay} must be inside {root}")
        self.overlay_rel = overlay.relative_to(root).as_posix()
        self.core = root / self.core_rel
        self.overlay = overlay
        self.scripts_rel = self.rel(self.core_rel, "scripts")
        self.marker = f"Generated by {self.scripts_rel}/render_adapters.py; edit canonical sources."

    def localize(self, core_text: str) -> str:
        """Core text names the default locations; point them at this checkout's layout."""
        return (core_text.replace("harness/project/", f"{self.overlay_rel}/")
                .replace("harness/core/", f"{self.core_rel}/"))

    @staticmethod
    def rel(*parts: str) -> str:
        return posixpath.normpath(posixpath.join(*parts))


def core_location(root: Path) -> str:
    core = project.core_root()
    if core.is_relative_to(root):
        location = core.relative_to(root).as_posix()
    elif (root / "harness/core").resolve() == core:
        location = "harness/core"  # A symlink to the core checkout while developing it.
    else:
        raise ValueError(f"the core {core} is outside {root}: vendor it at harness/core "
                         "(git subtree, or a symlink to the core checkout while developing it)")
    if location == ".":
        raise ValueError(f"{root} is the core itself; render a project with --root <repository>")
    return location


def frontmatter(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines or lines[0] != "---":
        raise ValueError(f"{path}: missing YAML frontmatter")
    try:
        end = lines.index("---", 1)
    except ValueError as exc:
        raise ValueError(f"{path}: unterminated YAML frontmatter") from exc
    return "\n".join(lines[1:end])


def scalar(header: str, key: str, source: Path) -> str:
    """Read required scalar metadata from our deliberately small frontmatter schema."""
    match = re.search(rf"^{re.escape(key)}:[ \t]*(\S[^\n]*)$", header, re.MULTILINE)
    if not match:
        raise ValueError(f"{source}: missing {key} metadata")
    value = match.group(1).strip()
    if value.startswith('"'):
        value = json.loads(value)
    elif value.startswith("'") and value.endswith("'"):
        value = value[1:-1].replace("''", "'")
    elif value in ("|", ">", "|-", ">-", "|+", ">+"):
        rest = header[match.end():].splitlines()
        value = " ".join(line.strip() for line in rest if line.startswith(" "))
    if not isinstance(value, str) or not value.strip() or value.lower() in ("null", "~"):
        raise ValueError(f"{source}: empty {key} metadata")
    return value


def load_object(path: Path) -> dict:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"{path}: expected a JSON object")
    return value


def deep_merge(base: dict, override: dict) -> dict:
    merged = dict(base)
    for key, value in override.items():
        if isinstance(merged.get(key), dict) and isinstance(value, dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def role_instructions(runtime: str, rules: str) -> str:
    # Claude roles skip the auto-loaded CLAUDE.md (omitClaudeMd) and read the map once;
    # Codex loads AGENTS.md by itself, so naming it again would only re-read it.
    agents = ("Read AGENTS.md (the repository map) before acting, then only "
              if runtime == "claude" else "AGENTS.md is already in your context. Before acting, read only ")
    return (
        "Resolve the repository root from the worktree assigned in your task "
        "(git -C <assigned-worktree> rev-parse --show-toplevel). Use that worktree "
        "for all commands and resolve the following paths against its root.\n"
        f"{agents}the {rules}/*.md, docs and code your brief names or the files in scope need.\n"
        "Preserve the runtime's approval and sandbox settings."
    )


def toml_string(value: str) -> str:
    # A multi-line literal keeps the role readable in diffs; fall back to an escaped string.
    if "'''" not in value and not re.search(r"[\x00-\x08\x0b-\x1f\x7f]", value):
        return f"'''\n{value}'''"
    return json.dumps(value, ensure_ascii=False)


def own_handler(path: Path, hooks: dict, event: str, generated: dict, markers: tuple[str, ...],
                matcher: str | None = None) -> None:
    """Own only this harness's handler for an event; preserve personal hooks and matchers."""
    groups = hooks.setdefault(event, [])
    if not isinstance(groups, list):
        raise ValueError(f"{path}: hooks.{event} must be a list")
    found = False
    for group in groups:
        if not isinstance(group, dict) or not isinstance(group.get("hooks"), list):
            raise ValueError(f"{path}: invalid {event} hook group")
        handlers = []
        for handler in group["hooks"]:
            if not isinstance(handler, dict):
                raise ValueError(f"{path}: invalid {event} handler")
            old_command = handler.get("command", "")
            owned = isinstance(old_command, str) and any(m in old_command for m in markers)
            if owned:
                if not found:
                    handlers.append(generated)
                    found = True
            else:
                handlers.append(handler)
        group["hooks"] = handlers
    if not found:
        group = {"matcher": matcher} if matcher else {}
        groups.append({**group, "hooks": [generated]})


def hook_config(layout: Layout, relative: str, runtime: str) -> str:
    path = layout.root / relative
    config = load_object(path) if path.exists() else {}
    hooks = config.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError(f"{path}: hooks must be an object")
    scripts = layout.scripts_rel

    def owned(script: str) -> tuple[str, ...]:
        # The pre-core path too, so a migrated checkout gets its handler replaced, not doubled.
        return f"{scripts}/{script}", f"{LEGACY_SCRIPTS}/{script}"

    top = f'"$(git rev-parse --show-toplevel)/{scripts}'
    stop = {"type": "command", "command": f'python3 {top}/runtime_hook.py" --runtime {runtime}',
            "timeout": 15}
    if runtime == "claude":
        stop["statusMessage"] = "Checking shared harness gates"
    own_handler(path, hooks, "Stop", stop, (*owned("runtime_hook.py"), ".claude/hooks/check_docs_drift.py"))
    # Hard limits (push, deploy, broad staging, .env, personal files, skipped tests) are a
    # hook, not prose: compaction cannot drop it and every model hits the same wall.
    guarded = {"claude": "Bash|Read|Grep|Edit|Write|NotebookEdit", "codex": "Bash|apply_patch|Edit|Write"}
    # The project dir, not the agent's cwd: after `cd /tmp` git cannot find the checkout.
    root = ("${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null)}" if runtime == "claude"
            else "$(git rev-parse --show-toplevel 2>/dev/null)")
    deny = json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse", "permissionDecision": "deny",
        "permissionDecisionReason": f"The harness guard ({scripts}/guard.py) is missing here, "
                                    "so tool calls are denied until it is restored."}})
    # A crash inside the guard fails open (|| true); a missing guard fails closed.
    guard = {"type": "command", "timeout": 10,
             "command": f'g="{root}/{scripts}/guard.py"; if [ -f "$g" ]; then '
                        f'python3 "$g" --runtime {runtime} || true; else printf \'%s\\n\' \'{deny}\'; fi'}
    own_handler(path, hooks, "PreToolUse", guard, owned("guard.py"), matcher=guarded[runtime])
    if runtime == "claude":
        # Measured: 0.33 % of subagent request gaps exceed five minutes, so the
        # 1h cache write (2x) costs more than the rare 5-minute expiry.
        config["subagentPromptCacheTtl"] = "5m"
        # The orchestrator dispatches through the Agent tool; Codex runs only as a
        # herdr worker, and its orchestrator calls `tripwire.py check` itself.
        tripwire = {"type": "command", "command": f'python3 {top}/tripwire.py" hook || true',
                    "timeout": 30, "statusMessage": "Checking unit tripwires"}
        own_handler(path, hooks, "PostToolUse", tripwire, owned("tripwire.py"), matcher="Agent")
    return json.dumps(config, indent=2, ensure_ascii=False) + "\n"


def link_target(base: str, name: str) -> str:
    """A skill link sits at <runtime>/skills/<name>, two levels below the root."""
    return Layout.rel("../..", base, "skills", name)


def skill_links(layout: Layout) -> tuple[dict[str, str], list[str]]:
    sources: dict[str, list[str]] = {}
    for base, directory in ((layout.core_rel, layout.core), (layout.overlay_rel, layout.overlay)):
        for path in sorted((directory / "skills").glob("*/SKILL.md")):
            header = frontmatter(path)
            name = scalar(header, "name", path)
            scalar(header, "description", path)
            if not SAFE_NAME.fullmatch(name) or name != path.parent.name:
                raise ValueError(f"{path}: name must match its lowercase directory name")
            sources.setdefault(name, []).append(base)
    if not sources:
        raise ValueError(f"{layout.core_rel}/skills, {layout.overlay_rel}/skills: no skills found")
    links: dict[str, str] = {}
    notes = []
    for name, bases in sorted(sources.items()):
        if len(bases) > 1:
            notes.append(f"Project skill {name} overrides the core skill "
                         f"({layout.overlay_rel}/skills/{name} wins over {layout.core_rel}/skills/{name}).")
        for runtime_dir in (".agents", ".claude"):
            links[f"{runtime_dir}/skills/{name}"] = link_target(bases[-1], name)
    return links, notes


def role_declaration(name: str, metadata, source: str) -> dict:
    if not SAFE_NAME.fullmatch(name) or not isinstance(metadata, dict):
        raise ValueError(f"{source}: invalid role declaration: {name}")
    description, profile = metadata.get("description"), metadata.get("profile")
    if not isinstance(description, str) or not description.strip() or not isinstance(profile, str):
        raise ValueError(f"{source}: {name}: description and profile are required")
    tools, sandbox = metadata.get("tools"), metadata.get("sandbox", "workspace-write")
    if tools is not None and (not isinstance(tools, list) or not tools
                              or not all(isinstance(t, str) and t for t in tools)):
        raise ValueError(f"{source}: {name}: tools must be a non-empty list of tool names")
    if sandbox not in SANDBOXES:
        raise ValueError(f"{source}: {name}: sandbox must be one of {', '.join(SANDBOXES)}")
    return {"description": description, "profile": profile, "tools": tools, "sandbox": sandbox}


def composed_roles(layout: Layout) -> dict[str, tuple[dict, str, list[str]]]:
    """Each role: (declaration, composed text, source paths relative to the root)."""
    core_manifest = f"{layout.core_rel}/roles/manifest.json"
    manifest = load_object(layout.root / core_manifest)
    core_bodies = {p.stem for p in (layout.core / "roles").glob("*.md")}
    if core_bodies != set(manifest):
        raise ValueError(f"{core_manifest}: role manifest mismatch: missing bodies="
                         f"{sorted(set(manifest) - core_bodies)}, undeclared bodies="
                         f"{sorted(core_bodies - set(manifest))}")
    project_json = f"{layout.overlay_rel}/project.json"
    declared = project.load(layout.root, "project.json", {}).get("roles", {})
    if not isinstance(declared, dict):
        raise ValueError(f"{project_json}: roles must be an object of role declarations")
    overlay_bodies = {p.stem for p in (layout.overlay / "roles").glob("*.md")}
    declarations = {name: role_declaration(name, manifest[name], core_manifest) for name in manifest}
    for name in sorted(declared):
        declaration = role_declaration(name, declared[name], project_json)
        if name in manifest:
            raise ValueError(f"{project_json}: project role {name} is a core role; put its project "
                             f"specifics in {layout.overlay_rel}/roles/{name}.md instead")
        if name not in overlay_bodies:
            raise ValueError(f"{project_json}: project role {name} has no body "
                             f"{layout.overlay_rel}/roles/{name}.md")
        declarations[name] = declaration
    for name in sorted(overlay_bodies - set(manifest) - set(declared)):
        raise ValueError(f"{layout.overlay_rel}/roles/{name}.md: neither a core role nor declared "
                         f"under roles in {project_json}")

    def text(relative: str) -> str:
        return (layout.root / relative).read_text(encoding="utf-8").strip()

    roles = {}
    for name, declaration in sorted(declarations.items()):
        local = f"{layout.overlay_rel}/roles/{name}.md"
        if name in manifest:
            core = f"{layout.core_rel}/roles/{name}.md"
            body, sources = layout.localize(text(core)), [core]
            if name in overlay_bodies:
                body = f"{body}\n\n## Project specifics\n\n{text(local)}"
                sources.append(local)
        else:
            body, sources = text(local), [local]
        roles[name] = (declaration, body + "\n", sources)
    return roles


def agent_files(layout: Layout, files: dict[str, str]) -> None:
    models = deep_merge(load_object(layout.core / "adapters/models.json"),
                        project.load(layout.root, "models.json", {}))
    rules = f"{layout.overlay_rel}/rules"
    for name, (role, body, sources) in composed_roles(layout).items():
        source = ", ".join(sources)
        for runtime in ("claude", "codex"):
            settings = models.get(runtime, {}).get(role["profile"], {})
            model, effort = settings.get("model"), settings.get("effort")
            if not all(isinstance(v, str) and v.strip() for v in (model, effort)):
                raise ValueError(f"{runtime}/{role['profile']}: model and effort are required")
            instructions = f"{role_instructions(runtime, rules)}\n\n{body}"
            if runtime == "claude":
                header = {"name": name, "description": role["description"],
                          "model": model, "effort": effort}
                if role["tools"]:
                    header["tools"] = ", ".join(role["tools"])
                header["omitClaudeMd"] = True
                files[f".claude/agents/{name}.md"] = (
                    "---\n" + "".join(f"{k}: {json.dumps(v, ensure_ascii=False)}\n"
                                      for k, v in header.items())
                    + f"---\n\n<!-- {layout.marker} -->\n<!-- Source: {source} -->\n\n{instructions}"
                )
            else:
                config = {"name": name, "description": role["description"], "model": model,
                          "model_reasoning_effort": effort, "sandbox_mode": role["sandbox"]}
                content = (f"# {layout.marker}\n# Source: {source}\n"
                           + "".join(f"{k} = {json.dumps(v, ensure_ascii=False)}\n" for k, v in config.items())
                           + f"developer_instructions = {toml_string(instructions)}\n")
                # Validate the native format, and that it carries the role intact, before publishing.
                if tomllib.loads(content).get("developer_instructions") != instructions:
                    raise ValueError(f"{name}: role text does not survive TOML encoding")
                files[f".codex/agents/{name}.toml"] = content


def outputs(layout: Layout) -> tuple[dict[str, str], dict[str, str], list[str]]:
    root = layout.root
    files: dict[str, str] = {}
    links, notes = skill_links(layout)
    agent_files(layout, files)
    for path in sorted((layout.overlay / "rules").glob("*.md")):
        header = frontmatter(path)
        if not re.search(r"^paths:[ \t]*\S", header, re.MULTILINE):
            raise ValueError(f"{path}: paths metadata is required")
        # Carry the text: a pointer made every agent open a second file per rule.
        body = path.read_text(encoding="utf-8").split("\n---\n", 1)[1].lstrip("\n")
        files[f".claude/rules/{path.name}"] = (
            f"---\n{header}\n---\n\n<!-- {layout.marker} -->\n"
            f"<!-- Source: {layout.overlay_rel}/rules/{path.name} -->\n\n{body}"
        )
    for relative, runtime in ((".claude/settings.json", "claude"), (".codex/hooks.json", "codex")):
        files[relative] = hook_config(layout, relative, runtime)
    claude_path = root / "CLAUDE.md"
    claude_content = claude_path.read_text(encoding="utf-8") if claude_path.exists() else ""
    if not re.search(r"^@AGENTS\.md\s*$", claude_content, re.MULTILINE):
        claude_content = "@AGENTS.md\n" + ("\n" + claude_content if claude_content else "")
    files["CLAUDE.md"] = claude_content
    config_path = root / ".codex/config.toml"
    if config_path.exists():
        content = config_path.read_text(encoding="utf-8")
        tomllib.loads(content)
    else:
        content = (f"# {layout.marker}\n"
                   "# Project agents are in .codex/agents; shared skills are in .agents/skills.\n"
                   "# Runtime permissions and approval policy remain user-controlled.\n")
    files[".codex/config.toml"] = content
    return files, links, notes


def stale_outputs(layout: Layout, files: dict[str, str], links: dict[str, str]) -> list[Path]:
    """Find retired adapters using positive ownership evidence, never file names alone."""
    root = layout.root
    stale = []
    for directory, pattern, marker in (
        (".claude/agents", "*.md", OWNED_MD),
        (".codex/agents", "*.toml", OWNED_TOML),
        (".claude/rules", "*.md", OWNED_MD),
    ):
        for path in sorted((root / directory).glob(pattern)):
            relative = path.relative_to(root).as_posix()
            if relative in files or path.is_symlink() or not path.is_file():
                continue
            if any(marker.fullmatch(line) for line in path.read_text(encoding="utf-8").splitlines()):
                stale.append(path)
    # "." is the layout before the core was vendored: skills lived at the root.
    bases = (layout.core_rel, layout.overlay_rel, ".")
    for directory in (".agents/skills", ".claude/skills"):
        for path in sorted((root / directory).glob("*")):
            relative = path.relative_to(root).as_posix()
            if relative in links or not path.is_symlink():
                continue
            if os.readlink(path) in {link_target(base, path.name) for base in bases}:
                stale.append(path)
    return stale


def render(root: Path, check: bool) -> int:
    layout = Layout(root)
    files, links, notes = outputs(layout)
    # Preflight all collisions so a personal skill never causes a partial render.
    for relative in links:
        path = root / relative
        if path.exists() and not path.is_symlink():
            raise ValueError(f"refusing to replace personal skill directory/file: {path}")
    for relative in files:
        path = root / relative
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise ValueError(f"refusing to overwrite non-regular generated file: {path}")
    stale = stale_outputs(layout, files, links)
    drift = [f"{path.relative_to(root).as_posix()} (retired)" for path in stale]
    if not check:
        for path in stale:
            path.unlink()
    for relative, target in links.items():
        path = root / relative
        if path.is_symlink() and os.readlink(path) == target:
            continue
        drift.append(relative)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            if path.is_symlink():
                path.unlink()
            path.symlink_to(target, target_is_directory=True)
    for relative, content in files.items():
        path = root / relative
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        drift.append(relative)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    for note in notes:
        print(note)
    if check and drift:
        print(f"Adapter drift (run python3 {layout.scripts_rel}/render_adapters.py):\n  "
              + "\n  ".join(drift), file=sys.stderr)
        return 1
    print("Adapters are current." if check else f"Rendered {len(drift)} adapter entries.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path,
                        help="repository to render (default: the Git checkout of the current directory)")
    parser.add_argument("--check", action="store_true", help="Report drift without writing files")
    args = parser.parse_args()
    try:
        root = args.root.resolve() if args.root else project.repo_root()
        return render(root, args.check)
    except (OSError, ValueError, TypeError, AttributeError, project.OverlayError) as exc:
        print(f"Adapter error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
